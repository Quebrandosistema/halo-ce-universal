/*
WIN32_D3D11_TEXTURES.C

The Direct3D 11 backend's textures (port/windows/D3D11.md, phase 6, step 2):
the game's textures made and written through the device's copy of the
texture cache (xbox_textures_d3d11.c), their shader resource views, the
read-back for debug.texture_dump_directory, and (step 5) the mip
composites. A texture is a DEFAULT 2D, 3D or cube texture of the format the
copy decoded to (B8G8R8A8_UNORM, R8G8B8A8_UNORM for the high-res PNGs, or
BC1 to BC3 as they are), with a shader resource view over every level; each
level and face is written with UpdateSubresource (the texels copied during
the call, so they are the game's as they were then), the whole subresource
or a box of it (the text atlas's rows); the levels of a texture made for it
are generated by the device (GenerateMips, which needs RENDER_TARGET and
MISC_GENERATE_MIPS). A freed texture's handle is reused: the runtime keeps a
resource alive while queued draws read it, so the release is at once. The
sixth unit of the backend, sharing win32_d3d11.h.
*/

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "win32_d3d11.h"

_Static_assert(D3D11_BACKEND_TEXTURE_FORMAT_BGRA8 == DXGI_FORMAT_B8G8R8A8_UNORM &&
	D3D11_BACKEND_TEXTURE_FORMAT_RGBA8 == DXGI_FORMAT_R8G8B8A8_UNORM && D3D11_BACKEND_TEXTURE_FORMAT_BC1 == DXGI_FORMAT_BC1_UNORM &&
	D3D11_BACKEND_TEXTURE_FORMAT_BC2 == DXGI_FORMAT_BC2_UNORM && D3D11_BACKEND_TEXTURE_FORMAT_BC3 == DXGI_FORMAT_BC3_UNORM,
	"texture formats");

struct texture
{
	/* NULL: a free handle */
	ID3D11Resource *resource;
	ID3D11ShaderResourceView *view;
	struct d3d11_backend_texture description;
	uint32_t bytes;
};

static struct
{
	struct texture *textures;
	uint32_t count, capacity;
	/* the free handles (from freed textures), a stack */
	uint32_t *free_handles;
	uint32_t free_count, free_capacity;
	uint32_t alive, alive_bytes, writes, write_bytes;
	/* the read-back's staging texture, kept while the size and format are
	the same */
	ID3D11Texture2D *staging;
	uint32_t staging_width, staging_height;
	DXGI_FORMAT staging_format;
	int failed_logged[4];
} T;

static struct texture *texture_at(uint32_t handle)
{
	return handle && handle <= T.count && T.textures[handle - 1].resource ? &T.textures[handle - 1] : NULL;
}

static int format_compressed(uint32_t format)
{
	return format == D3D11_BACKEND_TEXTURE_FORMAT_BC1 || format == D3D11_BACKEND_TEXTURE_FORMAT_BC2 ||
		format == D3D11_BACKEND_TEXTURE_FORMAT_BC3;
}

/* a level's bytes, for the statistics */
static uint32_t level_bytes(const struct d3d11_backend_texture *description, uint32_t level)
{
	uint32_t width = description->width >> level ? description->width >> level : 1;
	uint32_t height = description->height >> level ? description->height >> level : 1;
	uint32_t depth = description->depth >> level ? description->depth >> level : 1;

	if (format_compressed(description->format))
		return ((width + 3) / 4) * ((height + 3) / 4) * (description->format == D3D11_BACKEND_TEXTURE_FORMAT_BC1 ? 8 : 16) * depth;
	return width * height * depth * 4;
}

static void failed_once(int which, const char *what, HRESULT result, const struct d3d11_backend_texture *description)
{
	if (T.failed_logged[which])
		return;
	T.failed_logged[which] = 1;
	platform_log("d3d11: %s (kind %u, format %u, %ux%ux%u, %u levels) was not made (%s; logged once)", what,
		description->kind, description->format, description->width, description->height, description->depth,
		description->levels, hr_text(result));
}

uint32_t d3d11_backend_texture_create(const struct d3d11_backend_texture *in)
{
	struct texture *texture;
	uint32_t handle, level, faces;
	HRESULT result;
	UINT bind = D3D11_BIND_SHADER_RESOURCE, misc = 0;

	if (!B.device || B.lost || !in->width || !in->height || !in->depth || !in->levels)
		return 0;
	if (in->kind != D3D11_BACKEND_TEXTURE_KIND_2D && in->kind != D3D11_BACKEND_TEXTURE_KIND_3D &&
		in->kind != D3D11_BACKEND_TEXTURE_KIND_CUBE)
		return 0;
	if (in->format != D3D11_BACKEND_TEXTURE_FORMAT_BGRA8 && in->format != D3D11_BACKEND_TEXTURE_FORMAT_RGBA8 &&
		!format_compressed(in->format))
		return 0;
	if (in->generate_mips)
	{
		bind |= D3D11_BIND_RENDER_TARGET;
		misc |= D3D11_RESOURCE_MISC_GENERATE_MIPS;
	}
	/* the handle: a freed one, or the next */
	if (T.free_count)
	{
		handle = T.free_handles[--T.free_count];
	}
	else
	{
		if (T.count == T.capacity)
		{
			uint32_t capacity = T.capacity ? T.capacity * 2 : 256;
			struct texture *grown = realloc(T.textures, capacity * sizeof(*grown));

			if (!grown)
				return 0;
			T.textures = grown;
			T.capacity = capacity;
		}
		handle = ++T.count;
	}
	texture = &T.textures[handle - 1];
	memset(texture, 0, sizeof(*texture));
	texture->description = *in;
	faces = in->kind == D3D11_BACKEND_TEXTURE_KIND_CUBE ? 6 : 1;
	if (in->kind == D3D11_BACKEND_TEXTURE_KIND_3D)
	{
		D3D11_TEXTURE3D_DESC description;

		memset(&description, 0, sizeof(description));
		description.Width = in->width;
		description.Height = in->height;
		description.Depth = in->depth;
		description.MipLevels = in->levels;
		description.Format = (DXGI_FORMAT)in->format;
		description.Usage = D3D11_USAGE_DEFAULT;
		description.BindFlags = bind;
		description.MiscFlags = misc;
		result = ID3D11Device_CreateTexture3D(B.device, &description, NULL, (ID3D11Texture3D **)&texture->resource);
	}
	else
	{
		D3D11_TEXTURE2D_DESC description;

		memset(&description, 0, sizeof(description));
		description.Width = in->width;
		description.Height = in->height;
		description.MipLevels = in->levels;
		description.ArraySize = faces;
		description.Format = (DXGI_FORMAT)in->format;
		description.SampleDesc.Count = 1;
		description.Usage = D3D11_USAGE_DEFAULT;
		description.BindFlags = bind;
		description.MiscFlags = misc | (faces == 6 ? D3D11_RESOURCE_MISC_TEXTURECUBE : 0);
		result = ID3D11Device_CreateTexture2D(B.device, &description, NULL, (ID3D11Texture2D **)&texture->resource);
	}
	if (SUCCEEDED(result))
		result = ID3D11Device_CreateShaderResourceView(B.device, texture->resource, NULL, &texture->view);
	if (backend_failed(result, "a texture"))
	{
		failed_once(0, "a texture", result, in);
		release(&texture->view);
		release(&texture->resource);
		/* (the handle goes back) */
		if (handle == T.count)
			T.count--;
		else if (T.free_count < T.free_capacity)
			T.free_handles[T.free_count++] = handle;
		return 0;
	}
	for (level = 0; level < in->levels; level++)
		texture->bytes += level_bytes(in, level) * faces;
	T.alive++;
	T.alive_bytes += texture->bytes;
	return handle;
}

int d3d11_backend_texture_write(uint32_t handle, uint32_t face, uint32_t level, const void *texels, uint32_t row_pitch,
	uint32_t slice_pitch, const uint32_t *box)
{
	struct texture *texture = texture_at(handle);
	D3D11_BOX region;
	UINT subresource;

	if (!B.device || B.lost || !texture || !texels || level >= texture->description.levels ||
		face >= (texture->description.kind == D3D11_BACKEND_TEXTURE_KIND_CUBE ? 6u : 1u))
	{
		return 0;
	}
	subresource = level + face * texture->description.levels;
	if (box)
	{
		region.left = box[0];
		region.top = box[1];
		region.right = box[2];
		region.bottom = box[3];
		region.front = 0;
		region.back = 1;
		if (region.left >= region.right || region.top >= region.bottom)
			return 1;
	}
	ID3D11DeviceContext_UpdateSubresource(B.context, texture->resource, subresource, box ? &region : NULL, texels,
		row_pitch, slice_pitch);
	T.writes++;
	T.write_bytes += box ? (region.right - region.left) * (region.bottom - region.top) * 4 :
		level_bytes(&texture->description, level);
	return 1;
}

void d3d11_backend_texture_generate_mips(uint32_t handle)
{
	struct texture *texture = texture_at(handle);

	if (!B.device || B.lost || !texture || !texture->description.generate_mips || texture->description.levels < 2)
		return;
	ID3D11DeviceContext_GenerateMips(B.context, texture->view);
}

ID3D11ShaderResourceView *d3d11_backend_texture_view(uint32_t handle)
{
	struct texture *texture = texture_at(handle);

	return texture ? texture->view : NULL;
}

/* level 0 of a 2D texture, BGRA or RGBA rows from the top as the texture
has them, through a staging texture (the Map waits for the GPU) */
int d3d11_backend_texture_read(uint32_t handle, void *pixels, size_t size)
{
	struct texture *texture = texture_at(handle);
	D3D11_TEXTURE2D_DESC description;
	D3D11_MAPPED_SUBRESOURCE mapped;
	uint32_t row, width, height;
	HRESULT result;

	if (!B.device || B.lost || !texture || texture->description.kind != D3D11_BACKEND_TEXTURE_KIND_2D ||
		format_compressed(texture->description.format))
	{
		return 0;
	}
	width = texture->description.width;
	height = texture->description.height;
	if (size < (size_t)width * height * 4)
		return 0;
	if (!T.staging || T.staging_width != width || T.staging_height != height ||
		T.staging_format != (DXGI_FORMAT)texture->description.format)
	{
		release(&T.staging);
		memset(&description, 0, sizeof(description));
		description.Width = width;
		description.Height = height;
		description.MipLevels = 1;
		description.ArraySize = 1;
		description.Format = (DXGI_FORMAT)texture->description.format;
		description.SampleDesc.Count = 1;
		description.Usage = D3D11_USAGE_STAGING;
		description.CPUAccessFlags = D3D11_CPU_ACCESS_READ;
		result = ID3D11Device_CreateTexture2D(B.device, &description, NULL, &T.staging);
		if (backend_failed(result, "a texture read-back's staging texture"))
		{
			failed_once(1, "a texture read-back's staging texture", result, &texture->description);
			return 0;
		}
		T.staging_width = width;
		T.staging_height = height;
		T.staging_format = description.Format;
	}
	ID3D11DeviceContext_CopySubresourceRegion(B.context, (ID3D11Resource *)T.staging, 0, 0, 0, 0, texture->resource, 0,
		NULL);
	result = ID3D11DeviceContext_Map(B.context, (ID3D11Resource *)T.staging, 0, D3D11_MAP_READ, 0, &mapped);
	if (backend_failed(result, "Map (a texture read-back)"))
		return 0;
	for (row = 0; row < height; row++)
		memcpy((char *)pixels + (size_t)row * width * 4, (const char *)mapped.pData + (size_t)row * mapped.RowPitch,
			(size_t)width * 4);
	ID3D11DeviceContext_Unmap(B.context, (ID3D11Resource *)T.staging, 0);
	return 1;
}

void d3d11_backend_texture_free(uint32_t handle)
{
	struct texture *texture = texture_at(handle);

	if (!texture)
		return;
	release(&texture->view);
	release(&texture->resource);
	T.alive--;
	T.alive_bytes -= texture->bytes;
	memset(texture, 0, sizeof(*texture));
	if (T.free_count == T.free_capacity)
	{
		uint32_t capacity = T.free_capacity ? T.free_capacity * 2 : 256;
		uint32_t *grown = realloc(T.free_handles, capacity * sizeof(*grown));

		if (!grown)
			return;
		T.free_handles = grown;
		T.free_capacity = capacity;
	}
	T.free_handles[T.free_count++] = handle;
}

uint32_t d3d11_backend_textures_alive(uint32_t *bytes)
{
	if (bytes)
		*bytes = T.alive_bytes;
	return T.alive;
}

/* ---------- the mip composites (step 5) */

ID3D11ShaderResourceView *d3d11_backend_composite_view(uint32_t handle)
{
	(void)handle;
	return NULL;
}

/* ---------- the statistics, the release */

void d3d11_backend_textures_statistics(uint32_t counts[D3D11_BACKEND_DRAW_STATISTICS])
{
	counts[D3D11_BACKEND_DRAW_STATISTIC_TEXTURE_WRITES] = T.writes;
	counts[D3D11_BACKEND_DRAW_STATISTIC_TEXTURE_WRITE_BYTES] = T.write_bytes;
	counts[D3D11_BACKEND_DRAW_STATISTIC_TEXTURES_ALIVE] = T.alive;
	counts[D3D11_BACKEND_DRAW_STATISTIC_TEXTURE_BYTES] = T.alive_bytes;
}

void d3d11_backend_textures_release(void)
{
	uint32_t index;

	release(&T.staging);
	for (index = 0; index < T.count; index++)
	{
		release(&T.textures[index].view);
		release(&T.textures[index].resource);
	}
	free(T.textures);
	free(T.free_handles);
	memset(&T, 0, sizeof(T));
}
