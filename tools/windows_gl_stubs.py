#!/usr/bin/env python3
"""Generate the Direct3D 11 executable's counted GL stubs.

halo_d3d11.exe (port/windows/D3D11.md, phase 1) links the platform layer's
shared files, some of which still call OpenGL through gl.h's halo_gl*
pointers (hud_hires.c, text_hires.c, menu_files.c, xbox_textures.c). It has no
GL context, so it leaves gl_functions.c out, whose pointers would be null,
and links the file this writes instead: for every function of gl.h's desktop
list, a stub with the function's own signature that counts the call and
returns 0 (or nothing), and the halo_<function> pointer gl.h declares, set
to it.

The signature matters: GL's entry points are APIENTRY, __stdcall on 32-bit
Windows, where the callee pops its arguments, so a stub with the wrong
parameters would unbalance the caller's stack. The prototypes come from
SDL's GL headers (the ones gl.h includes), and the pointer's definition,
__typeof__(&<function>), makes the compiler check each stub against them.

The stubs write no output parameter: a glGenTextures leaves the name it is
given as it was, a glGetIntegerv the value. Phase 6 replaces each caller
(port/windows/D3D11.md, "The GL stubs").

Usage: windows_gl_stubs.py gl.h SDL_opengl.h SDL_opengl_glext.h output.c
"""

import re
import sys


def desktop_functions(gl_header: str):
    """the desktop GL_FUNCTIONS(X) list of gl.h: the one after the Android list"""
    text = open(gl_header, encoding="utf-8").read()
    start = text.index("/* ANDROID_GL_FUNCTIONS_END */")
    end = text.index("#endif", text.index("#define GL_FUNCTIONS(X)", start))
    names = re.findall(r"X\((\w+)\)", text[start:end])
    if not names:
        raise SystemExit(f"{gl_header}: no desktop GL_FUNCTIONS list")
    return names


def prototypes(*headers):
    """{name: (return type, parameters)} from 'GLAPI <return> [GL]APIENTRY <name> (<parameters>);'"""
    result = {}
    pattern = re.compile(r"GLAPI\s+([^;{}]+?)\s*\b(?:GLAPIENTRY|APIENTRY)\s+(\w+)\s*\(([^;{}]*?)\)\s*;", re.S)
    for header in headers:
        text = open(header, encoding="utf-8").read()
        for ret, name, params in pattern.findall(text):
            result.setdefault(name, (" ".join(ret.split()), " ".join(params.split())))
    return result


def parameter_type(name: str, param: str) -> str:
    """a parameter's type, without its name"""
    match = re.match(r"^(.*?[\s*])(\w+)$", param.strip())
    if not match or not match.group(1).strip() or match.group(2) in ("void", "GLenum", "GLint", "GLuint"):
        raise SystemExit(f"{name}: cannot tell the parameter '{param}' from its type; add a case")
    return match.group(1).strip()


def main():
    gl_header, sdl_opengl, sdl_glext, output = sys.argv[1:5]
    functions = desktop_functions(gl_header)
    protos = prototypes(sdl_opengl, sdl_glext)
    missing = [name for name in functions if name not in protos]
    if missing:
        raise SystemExit(f"no prototype in SDL's GL headers for: {', '.join(missing)}")
    out = [
        "/* generated by tools/windows_gl_stubs.py from port/linux/src/gl.h and SDL's GL headers; do not edit",
        "",
        "The Direct3D 11 executable's GL entry points (port/windows/D3D11.md, \"The GL stubs\"): each counts",
        "its calls, logs its first caller, writes no output parameter and returns 0. */",
        "",
        '#include "platform.h"',
        "#define GL_FUNCTIONS_DEFINE",
        '#include "gl.h"',
        "",
        f"#define GL_STUB_COUNT {len(functions)}",
        "",
        "static const char *const gl_stub_names[GL_STUB_COUNT] =",
        "{",
    ]
    out += [f'\t"{name}",' for name in functions]
    out += [
        "};",
        "",
        "/* each stub's calls, and all of them */",
        "static unsigned long gl_stub_counts[GL_STUB_COUNT];",
        "static unsigned long gl_stub_total;",
        "",
        "/* the executable's base (the linker's), so that a caller's address is logged as an offset into it",
        "for llvm-symbolizer --relative-address */",
        "extern const char __ImageBase;",
        "",
        "static void gl_stub_called(int index, void *caller)",
        "{",
        "\t__atomic_add_fetch(&gl_stub_total, 1, __ATOMIC_RELAXED);",
        "\tif (__atomic_fetch_add(&gl_stub_counts[index], 1, __ATOMIC_RELAXED) == 0)",
        "\t{",
        '\t\tplatform_log("gl stub: %s called from %p (halo_d3d11.exe+0x%lx)", gl_stub_names[index], caller,',
        "\t\t\t(unsigned long)((const char *)caller - &__ImageBase));",
        "\t}",
        "}",
        "",
        "/* the calls counted since the start (d3d8_d3d11.c's statistics) */",
        "unsigned long gl_stubs_calls(void)",
        "{",
        "\treturn __atomic_load_n(&gl_stub_total, __ATOMIC_RELAXED);",
        "}",
        "",
        "/* gl_functions.c's, which sdl_platform.c calls on its OpenGL path: not taken here (the window has no",
        "context, platform_video_without_gl), and a failure if it were */",
        "int gl_functions_load(void)",
        "{",
        '\tplatform_log("gl stubs: gl_functions_load called, but the Direct3D 11 executable has no OpenGL context");',
        "\treturn 0;",
        "}",
        "",
    ]
    for index, name in enumerate(functions):
        ret, params = protos[name]
        if params in ("void", ""):
            types = []
        else:
            types = [parameter_type(name, p) for p in params.split(",")]
        declared = ", ".join(f"{t} a{i}" for i, t in enumerate(types)) or "void"
        out.append(f"static {ret} GLAPIENTRY stub_{name}({declared})")
        out.append("{")
        for i in range(len(types)):
            out.append(f"\t(void)a{i};")
        out.append(f"\tgl_stub_called({index}, __builtin_return_address(0));")
        if ret != "void":
            out.append("\treturn 0;")
        out.append("}")
        out.append(f"__typeof__(&{name}) halo_{name} = stub_{name};")
        out.append("")
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
